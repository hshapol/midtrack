export function getPollsterWeight(name) {
  if (!name) return 0.7;
  if (POLLSTER_WEIGHTS[name] !== undefined) return POLLSTER_WEIGHTS[name];
  const lower = name.toLowerCase();
  for (const [k, w] of Object.entries(POLLSTER_WEIGHTS)) {
    if (lower.includes(k.toLowerCase()) || k.toLowerCase().includes(lower)) return w;
  }
  return 0.7;
}
